-- Enable Anonymous Sign-Ins before connecting the frontend.
begin;

create table public.dramify_responses (
  id uuid primary key,
  auth_user_id uuid not null unique default auth.uid() references auth.users(id),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  access_code text not null check (access_code in ('20266202','62022026')),
  condition text generated always as (case access_code when '20266202' then 'A' else 'B' end) stored,
  nickname text not null check (char_length(trim(nickname)) between 1 and 50),
  gender text not null,
  age integer not null check (age between 1 and 120),
  country text not null,
  duration_seconds numeric not null default 0 check (duration_seconds >= 0),
  app_rating integer check (app_rating between 1 and 10),
  comment text not null default '' check (char_length(comment) <= 3000),
  drama_order integer[] not null,
  stimuli jsonb not null default '{}'::jsonb check (jsonb_typeof(stimuli) = 'object'),
  completed boolean not null default false
);

alter table public.dramify_responses enable row level security;
revoke all on public.dramify_responses from anon, authenticated;
grant select, insert, update on public.dramify_responses to authenticated;
create policy "Participants read their own response"
  on public.dramify_responses for select to authenticated
  using ((select auth.uid()) = auth_user_id);
create policy "Participants create their own response"
  on public.dramify_responses for insert to authenticated
  with check ((select auth.uid()) = auth_user_id);
create policy "Participants update their own response"
  on public.dramify_responses for update to authenticated
  using ((select auth.uid()) = auth_user_id)
  with check ((select auth.uid()) = auth_user_id);
-- No participant DELETE policy or DELETE grant: sign out must retain research data.

alter table public.dramify_responses
  add column if not exists interface_version text not null default 'preorder-v2',
  add column if not exists behavior_counts jsonb not null default '{}'::jsonb,
  add column if not exists behavior_events jsonb not null default '[]'::jsonb;

